/**
 * Copy the Vite pages build to the repository root.
 *
 * GitHub Pages for this repo is a project site served from the root of `main`
 * (legacy "deploy from a branch"). It does not run Vite, so the compiled
 * index, assets, and public files have to live where Pages will publish them.
 */
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');
const builtHtmlPath = path.join(dist, 'index.dev.html');
const pagesBase = '/Mountain-Piper-website/';

const html = readFileSync(builtHtmlPath, 'utf8');
if (!html.includes(`${pagesBase}assets/`)) {
  throw new Error(
    `Built HTML does not reference ${pagesBase}assets/. Refusing to publish a bundle that would load blank on GitHub Pages.`,
  );
}

const publishedHtml = html
  .replace(
    '<!doctype html>',
    '<!doctype html>\n<!-- Generated by npm run build:pages from index.dev.html. Do not edit by hand. -->',
  )
  // Noscript links are root-absolute. Point them at this project site.
  .replace('href="/"', `href="${pagesBase}"`)
  .replace(/href="\/(weddings|funerals-memorials|events|lessons|about|contact)"/g, `href="${pagesBase}$1"`);

writeFileSync(path.join(root, 'index.html'), publishedHtml);
writeFileSync(path.join(root, '404.html'), publishedHtml);
writeFileSync(path.join(root, '.nojekyll'), '');

const assetsDir = path.join(root, 'assets');
rmSync(assetsDir, { recursive: true, force: true });
cpSync(path.join(dist, 'assets'), assetsDir, { recursive: true });

const imagesDir = path.join(root, 'images');
rmSync(imagesDir, { recursive: true, force: true });
mkdirSync(imagesDir, { recursive: true });
cpSync(path.join(dist, 'images'), imagesDir, { recursive: true });

for (const file of ['favicon.svg', 'robots.txt', 'sitemap.xml']) {
  cpSync(path.join(dist, file), path.join(root, file));
}

console.log('Published GitHub Pages files to the repository root.');
